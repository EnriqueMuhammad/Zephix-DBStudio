//! DDL generation from [`TableSchema`]: `CREATE TABLE`, and `ALTER TABLE` scripts that turn
//! one definition into another, per dialect.
//!
//! Column renames must be passed explicitly; otherwise a renamed column is indistinguishable
//! from dropping one column and adding another (which loses data).

use std::collections::HashMap;

use crate::dialect::{qualified_name, quote_identifier};
use crate::profile::DatabaseKind;
use crate::table::{ColumnDef, ForeignKeyDef, IndexDef, TableSchema};

/// Why a change cannot be expressed for a dialect.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0}")]
pub struct DdlError(pub String);

/// Joins statements into an executable script (`;` + newline after each).
pub fn script(statements: &[String]) -> String {
    statements
        .iter()
        .map(|s| format!("{s};"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn q(kind: DatabaseKind, name: &str) -> String {
    quote_identifier(kind, name)
}

fn table_name(kind: DatabaseKind, t: &TableSchema) -> String {
    qualified_name(kind, None, t.schema.as_deref(), &t.name)
}

fn column_list(kind: DatabaseKind, cols: &[String]) -> String {
    cols.iter()
        .map(|c| q(kind, c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Whether a type is an integer type (identity columns must be integers).
pub fn is_integer_type(data_type: &str) -> bool {
    let base = data_type.to_ascii_lowercase();
    [
        "int",
        "integer",
        "bigint",
        "smallint",
        "tinyint",
        "mediumint",
        "int2",
        "int4",
        "int8",
        "serial",
        "bigserial",
    ]
    .iter()
    .any(|t| base == *t || base.starts_with(&format!("{t} ")) || base.starts_with(&format!("{t}(")))
}

