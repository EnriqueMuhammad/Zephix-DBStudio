/// `name type …` for CREATE TABLE / ADD COLUMN / MODIFY.
pub fn column_definition(kind: DatabaseKind, c: &ColumnDef) -> String {
    let mut out = format!("{} {}", q(kind, &c.name), c.data_type);
    if kind == DatabaseKind::Oracle {
        // Oracle wants DEFAULT before the NOT NULL constraint.
        if c.identity {
            out.push_str(" GENERATED BY DEFAULT ON NULL AS IDENTITY");
        } else if let Some(default) = &c.default {
            out.push_str(&format!(" DEFAULT {default}"));
        }
        if !c.nullable {
            out.push_str(" NOT NULL");
        }
        return out;
    }
    if c.identity {
        match kind {
            DatabaseKind::PostgreSql => out.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            DatabaseKind::SqlServer => out.push_str(" IDENTITY(1,1)"),
            DatabaseKind::MySql | DatabaseKind::MariaDb => out.push_str(" AUTO_INCREMENT"),
            _ => {}
        }
    }
    match (kind, c.nullable) {
        (DatabaseKind::SqlServer, true) => out.push_str(" NULL"),
        (_, false) => out.push_str(" NOT NULL"),
        _ => {}
    }
    if let Some(default) = c.default.as_ref().filter(|_| !c.identity) {
        out.push_str(&format!(" DEFAULT {default}"));
    }
    out
}

fn fk_clause(kind: DatabaseKind, t: &TableSchema, fk: &ForeignKeyDef) -> String {
    let target = qualified_name(
        kind,
        None,
        fk.ref_schema.as_deref().or(t.schema.as_deref()),
        &fk.ref_table,
    );
    format!(
        "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {target} ({})",
        q(kind, &fk.name),
        column_list(kind, &fk.columns),
        column_list(kind, &fk.ref_columns)
    )
}

fn create_index(kind: DatabaseKind, t: &TableSchema, ix: &IndexDef) -> String {
    format!(
        "CREATE {}INDEX {} ON {} ({})",
        if ix.unique { "UNIQUE " } else { "" },
        q(kind, &ix.name),
        table_name(kind, t),
        column_list(kind, &ix.columns)
    )
}

fn unique_constraint(kind: DatabaseKind, ix: &IndexDef) -> String {
    format!(
        "CONSTRAINT {} UNIQUE ({})",
        q(kind, &ix.name),
        column_list(kind, &ix.columns)
    )
}

/// Adds an index, or a unique constraint, to an existing table.
fn add_index(kind: DatabaseKind, t: &TableSchema, ix: &IndexDef) -> String {
    if ix.constraint {
        format!(
            "ALTER TABLE {} ADD {}",
            table_name(kind, t),
            unique_constraint(kind, ix)
        )
    } else {
        create_index(kind, t, ix)
    }
}

fn drop_index(kind: DatabaseKind, t: &TableSchema, ix: &IndexDef) -> String {
    let name = ix.name.as_str();
    if ix.constraint && !matches!(kind, DatabaseKind::MySql | DatabaseKind::MariaDb) {
        return format!(
            "ALTER TABLE {} DROP CONSTRAINT {}",
            table_name(kind, t),
            q(kind, name)
        );
    }
    match kind {
        DatabaseKind::PostgreSql | DatabaseKind::Oracle => {
            format!(
                "DROP INDEX {}",
                qualified_name(kind, None, t.schema.as_deref(), name)
            )
        }
        DatabaseKind::Sqlite => format!("DROP INDEX {}", q(kind, name)),
        _ => format!("DROP INDEX {} ON {}", q(kind, name), table_name(kind, t)),
    }
}

fn pk_name(t: &TableSchema) -> String {
    t.primary_key_name
        .clone()
        .unwrap_or_else(|| format!("pk_{}", t.name))
}

/// `CREATE TABLE` followed by `CREATE INDEX` statements.
pub fn create_table(kind: DatabaseKind, t: &TableSchema) -> Vec<String> {
    // SQLite: a single integer identity key becomes `INTEGER PRIMARY KEY AUTOINCREMENT`.
    let sqlite_rowid_key = kind == DatabaseKind::Sqlite
        && t.primary_key.len() == 1
        && t.column(&t.primary_key[0]).is_some_and(|c| c.identity);
    let mut lines: Vec<String> = t
        .columns
        .iter()
        .map(|c| {
            if sqlite_rowid_key && t.primary_key[0] == c.name {
                format!("{} INTEGER PRIMARY KEY AUTOINCREMENT", q(kind, &c.name))
            } else {
                column_definition(kind, c)
            }
        })
        .map(|line| format!("    {line}"))
        .collect();
    if !t.primary_key.is_empty() && !sqlite_rowid_key {
        let cols = column_list(kind, &t.primary_key);
        lines.push(match kind {
            DatabaseKind::MySql | DatabaseKind::MariaDb | DatabaseKind::Sqlite => {
                format!("    PRIMARY KEY ({cols})")
            }
            _ => format!(
                "    CONSTRAINT {} PRIMARY KEY ({cols})",
                q(kind, &pk_name(t))
            ),
        });
    }
    for ix in t.indexes.iter().filter(|ix| ix.constraint) {
        lines.push(format!("    {}", unique_constraint(kind, ix)));
    }
    for fk in &t.foreign_keys {
        lines.push(format!("    {}", fk_clause(kind, t, fk)));
    }
    let mut out = vec![format!(
        "CREATE TABLE {} (\n{}\n)",
        table_name(kind, t),
        lines.join(",\n")
    )];
    out.extend(
        t.indexes
            .iter()
            .filter(|ix| !ix.constraint)
            .map(|ix| create_index(kind, t, ix)),
    );
    out
}

/// Renames table `t` to `new_name` (same schema).
pub fn rename_table(kind: DatabaseKind, t: &TableSchema, new_name: &str) -> String {
    match kind {
        DatabaseKind::SqlServer => {
            let path = table_name(kind, t).replace('\'', "''");
            format!(
                "EXEC sp_rename N'{path}', N'{}'",
                new_name.replace('\'', "''")
            )
        }
        _ => format!(
            "ALTER TABLE {} RENAME TO {}",
            table_name(kind, t),
            q(kind, new_name)
        ),
    }
}

/// `DROP TABLE`.
pub fn drop_table(kind: DatabaseKind, t: &TableSchema) -> String {
    format!("DROP TABLE {}", table_name(kind, t))
}

/// SQL Server: drops the (system-named) default constraint of a column, if any.
fn mssql_drop_default(t: &TableSchema, column: &str) -> String {
    let two_part = table_name(DatabaseKind::SqlServer, t).replace('\'', "''");
    let col = column.replace('\'', "''");
    format!(
        "DECLARE @df sysname = (SELECT name FROM sys.default_constraints \
         WHERE parent_object_id = OBJECT_ID(N'{two_part}') \
           AND parent_column_id = COLUMNPROPERTY(OBJECT_ID(N'{two_part}'), N'{col}', 'ColumnId')); \
         IF @df IS NOT NULL EXEC(N'ALTER TABLE {two_part} DROP CONSTRAINT [' + @df + N']')"
    )
}

/// Statements that change table `old` into `new`. `renames` maps old → new column names.
pub fn alter_table(
    kind: DatabaseKind,
    old: &TableSchema,
    new: &TableSchema,
    renames: &[(String, String)],
) -> Result<Vec<String>, DdlError> {
    if kind == DatabaseKind::Sqlite {
        return Ok(sqlite_alter(old, new, renames));
    }
    let table = table_name(kind, new);
    let rename_map: HashMap<&str, &str> = renames
        .iter()
        .map(|(a, b)| (a.as_str(), b.as_str()))
        .collect();
    // Old column name → its name in the new definition (if kept).
    let mapped = |old_name: &str| -> Option<String> {
        let target = rename_map.get(old_name).copied().unwrap_or(old_name);
        new.column(target).map(|c| c.name.clone())
    };
    let map_cols = |cols: &[String]| -> Vec<String> {
        cols.iter()
            .map(|c| mapped(c).unwrap_or_else(|| c.clone()))
            .collect()
    };

    let mut out = Vec::new();

    // 1. Foreign keys that disappear or change.
    let fk_same = |a: &ForeignKeyDef, b: &ForeignKeyDef| {
        a.name == b.name
            && map_cols(&a.columns) == b.columns
            && a.ref_table == b.ref_table
            && a.ref_columns == b.ref_columns
            && a.ref_schema == b.ref_schema
    };
    for fk in &old.foreign_keys {
        if !new.foreign_keys.iter().any(|n| fk_same(fk, n)) {
            out.push(match kind {
                DatabaseKind::MySql | DatabaseKind::MariaDb => {
                    format!("ALTER TABLE {table} DROP FOREIGN KEY {}", q(kind, &fk.name))
                }
                _ => format!("ALTER TABLE {table} DROP CONSTRAINT {}", q(kind, &fk.name)),
            });
        }
    }
    // 2. Indexes that disappear or change.
    let ix_same = |a: &IndexDef, b: &IndexDef| {
        a.name == b.name
            && a.unique == b.unique
            && a.constraint == b.constraint
            && map_cols(&a.columns) == b.columns
    };
    for ix in &old.indexes {
        if !new.indexes.iter().any(|n| ix_same(ix, n)) {
            out.push(drop_index(kind, old, ix));
        }
    }
    // 3. Primary key change (drop first).
    let pk_changed = map_cols(&old.primary_key) != new.primary_key;
    if pk_changed && !old.primary_key.is_empty() {
        out.push(match kind {
            DatabaseKind::MySql | DatabaseKind::MariaDb => {
                format!("ALTER TABLE {table} DROP PRIMARY KEY")
            }
            _ => {
                let name = old.primary_key_name.clone().ok_or_else(|| {
                    DdlError("the primary key constraint name is unknown; cannot drop it".into())
                })?;
                format!("ALTER TABLE {table} DROP CONSTRAINT {}", q(kind, &name))
            }
        });
    }
    // 4. Renames.
    for (from, to) in renames {
        if from == to || old.column(from).is_none() {
            continue;
        }
        out.push(match kind {
            DatabaseKind::SqlServer => {
                let path = format!("{}.{from}", table_name(kind, old)).replace('\'', "''");
                format!(
                    "EXEC sp_rename N'{path}', N'{}', 'COLUMN'",
                    to.replace('\'', "''")
                )
            }
            _ => format!(
                "ALTER TABLE {table} RENAME COLUMN {} TO {}",
                q(kind, from),
                q(kind, to)
            ),
        });
    }
    // 5. Dropped columns.
    for c in &old.columns {
        if mapped(&c.name).is_none() {
            if kind == DatabaseKind::SqlServer && c.default.is_some() {
                out.push(mssql_drop_default(old, &c.name));
            }
            out.push(format!(
                "ALTER TABLE {table} DROP COLUMN {}",
                q(kind, &c.name)
            ));
        }
    }
    // 6. Changed columns.
    for oc in &old.columns {
        let Some(new_name) = mapped(&oc.name) else {
            continue;
        };
        let Some(nc) = new.column(&new_name) else {
            continue;
        };
        let type_changed = !crate::types::equivalent_types(&oc.data_type, &nc.data_type);
        let null_changed = oc.nullable != nc.nullable;
        let default_changed =
            !crate::types::equivalent_defaults(oc.default.as_deref(), nc.default.as_deref());
        let identity_changed = oc.identity != nc.identity;
        if !(type_changed || null_changed || default_changed || identity_changed) {
            continue;
        }
        let col = q(kind, &nc.name);
        match kind {
            DatabaseKind::PostgreSql => {
                if type_changed {
                    out.push(format!(
                        "ALTER TABLE {table} ALTER COLUMN {col} TYPE {} USING {col}::{}",
                        nc.data_type, nc.data_type
                    ));
                }
                if null_changed {
                    let verb = if nc.nullable { "DROP" } else { "SET" };
                    out.push(format!(
                        "ALTER TABLE {table} ALTER COLUMN {col} {verb} NOT NULL"
                    ));
                }
                if identity_changed {
                    out.push(if nc.identity {
                        format!("ALTER TABLE {table} ALTER COLUMN {col} ADD GENERATED BY DEFAULT AS IDENTITY")
                    } else {
                        format!("ALTER TABLE {table} ALTER COLUMN {col} DROP IDENTITY IF EXISTS")
                    });
                }
                if default_changed {
                    out.push(match &nc.default {
                        Some(d) => {
                            format!("ALTER TABLE {table} ALTER COLUMN {col} SET DEFAULT {d}")
                        }
                        None => format!("ALTER TABLE {table} ALTER COLUMN {col} DROP DEFAULT"),
                    });
                }
            }
            DatabaseKind::MySql | DatabaseKind::MariaDb => {
                out.push(format!(
                    "ALTER TABLE {table} MODIFY COLUMN {}",
                    column_definition(kind, nc)
                ));
            }
            DatabaseKind::SqlServer => {
                if identity_changed {
                    return Err(DdlError(format!(
                        "SQL Server cannot add or remove IDENTITY on existing column {}; recreate the table",
                        nc.name
                    )));
                }
                // A default constraint blocks ALTER COLUMN, so it is dropped first and re-added.
                let recreate_default = default_changed || (type_changed && oc.default.is_some());
                if recreate_default {
                    out.push(mssql_drop_default(new, &nc.name));
                }
                if type_changed || null_changed {
                    let null = if nc.nullable { "NULL" } else { "NOT NULL" };
                    out.push(format!(
                        "ALTER TABLE {table} ALTER COLUMN {col} {} {null}",
                        nc.data_type
                    ));
                }
                if recreate_default && let Some(d) = &nc.default {
                    out.push(format!("ALTER TABLE {table} ADD DEFAULT {d} FOR {col}"));
                }
            }
            DatabaseKind::Oracle => {
                if identity_changed {
                    return Err(DdlError(format!(
                        "changing the identity of existing column {} is not supported on Oracle",
                        nc.name
                    )));
                }
                if type_changed {
                    out.push(format!(
                        "ALTER TABLE {table} MODIFY ({col} {})",
                        nc.data_type
                    ));
                }
                if default_changed {
                    let d = nc.default.as_deref().unwrap_or("NULL");
                    out.push(format!("ALTER TABLE {table} MODIFY ({col} DEFAULT {d})"));
                }
                if null_changed {
                    let null = if nc.nullable { "NULL" } else { "NOT NULL" };
                    out.push(format!("ALTER TABLE {table} MODIFY ({col} {null})"));
                }
            }
            DatabaseKind::Sqlite => unreachable!("handled above"),
            DatabaseKind::MongoDb | DatabaseKind::Redis => {
                return Err(DdlError(format!(
                    "{} has no table definitions",
                    kind.display_name()
                )));
            }
        }
    }
    // 7. Added columns.
    let kept: Vec<String> = old.columns.iter().filter_map(|c| mapped(&c.name)).collect();
    for nc in &new.columns {
        if kept.contains(&nc.name) {
            continue;
        }
        out.push(match kind {
            DatabaseKind::SqlServer => {
                format!("ALTER TABLE {table} ADD {}", column_definition(kind, nc))
            }
            DatabaseKind::Oracle => {
                format!("ALTER TABLE {table} ADD ({})", column_definition(kind, nc))
            }
            _ => format!(
                "ALTER TABLE {table} ADD COLUMN {}",
                column_definition(kind, nc)
            ),
        });
    }
    // 8. New primary key.
    if pk_changed && !new.primary_key.is_empty() {
        let cols = column_list(kind, &new.primary_key);
        out.push(match kind {
            DatabaseKind::MySql | DatabaseKind::MariaDb => {
                format!("ALTER TABLE {table} ADD PRIMARY KEY ({cols})")
            }
            _ => format!(
                "ALTER TABLE {table} ADD CONSTRAINT {} PRIMARY KEY ({cols})",
                q(kind, &pk_name(new))
            ),
        });
    }
    // 9. New or changed indexes.
    for ix in &new.indexes {
        if !old.indexes.iter().any(|o| ix_same(o, ix)) {
            out.push(add_index(kind, new, ix));
        }
    }
    // 10. New or changed foreign keys.
    for fk in &new.foreign_keys {
        if !old.foreign_keys.iter().any(|o| fk_same(o, fk)) {
            out.push(format!(
                "ALTER TABLE {table} ADD {}",
                fk_clause(kind, new, fk)
            ));
        }
    }
    Ok(out)
}

/// SQLite supports only ADD/RENAME/DROP COLUMN natively; anything else rebuilds the table:
/// create the new shape under a temporary name, copy the data, swap, recreate indexes.
fn sqlite_alter(old: &TableSchema, new: &TableSchema, renames: &[(String, String)]) -> Vec<String> {
    let kind = DatabaseKind::Sqlite;
    let rename_map: HashMap<&str, &str> = renames
        .iter()
        .map(|(a, b)| (a.as_str(), b.as_str()))
        .collect();
    let target = |old_name: &str| {
        rename_map
            .get(old_name)
            .copied()
            .unwrap_or(old_name)
            .to_owned()
    };

    // Simple case: only added columns (appended, nullable or with default) — ALTER suffices.
    let unchanged_prefix = old.columns.len() <= new.columns.len()
        && old.columns.iter().zip(&new.columns).all(|(o, n)| o == n)
        && old.primary_key == new.primary_key
        && old.foreign_keys == new.foreign_keys
        && renames.is_empty()
        // Unique constraints cannot be added or dropped without a rebuild.
        && old.indexes.iter().filter(|i| i.constraint).eq(new.indexes.iter().filter(|i| i.constraint));
    if unchanged_prefix {
        let table = table_name(kind, new);
        let mut out: Vec<String> = new.columns[old.columns.len()..]
            .iter()
            .map(|c| {
                format!(
                    "ALTER TABLE {table} ADD COLUMN {}",
                    column_definition(kind, c)
                )
            })
            .collect();
        for ix in &old.indexes {
            if !new.indexes.contains(ix) {
                out.push(drop_index(kind, old, ix));
            }
        }
        for ix in &new.indexes {
            if !old.indexes.contains(ix) {
                out.push(create_index(kind, new, ix));
            }
        }
        return out;
    }

    let temp = TableSchema {
        name: format!("{}__rdbs_new", new.name),
        indexes: new
            .indexes
            .iter()
            .filter(|i| i.constraint)
            .cloned()
            .collect(),
        ..new.clone()
    };
    let copied: Vec<(String, String)> = old
        .columns
        .iter()
        .filter_map(|c| {
            let to = target(&c.name);
            new.column(&to).map(|_| (c.name.clone(), to))
        })
        .collect();
    let mut out = vec!["PRAGMA foreign_keys = OFF".to_owned()];
    out.extend(create_table(kind, &temp));
    if !copied.is_empty() {
        out.push(format!(
            "INSERT INTO {} ({}) SELECT {} FROM {}",
            q(kind, &temp.name),
            copied
                .iter()
                .map(|(_, to)| q(kind, to))
                .collect::<Vec<_>>()
                .join(", "),
            copied
                .iter()
                .map(|(from, _)| q(kind, from))
                .collect::<Vec<_>>()
                .join(", "),
            q(kind, &old.name)
        ));
    }
    out.push(format!("DROP TABLE {}", q(kind, &old.name)));
    out.push(format!(
        "ALTER TABLE {} RENAME TO {}",
        q(kind, &temp.name),
        q(kind, &new.name)
    ));
    out.extend(
        new.indexes
            .iter()
            .filter(|ix| !ix.constraint)
            .map(|ix| create_index(kind, new, ix)),
    );
    out.push("PRAGMA foreign_keys = ON".to_owned());
    out
}

